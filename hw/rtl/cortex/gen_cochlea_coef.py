#!/usr/bin/env python3
"""Writes cochlea_coef.vh (the resonator shift-add terms) from hw/brain/cochlea_int.py. usage: python gen_cochlea_coef.py"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.join(HERE, "..", "..", "brain"))
import cochlea_int as ci  # noqa
lines = ["// Generated by gen_cochlea_coef.py from hw/brain/cochlea_int.py: per resonator k, 8 shift-add terms (4 for a1, then",
         "// 4 for a2), each {sign[1:0] (0 unused, 1 plus, 3 minus), exponent[5:0] signed}, then the gain exponent G[5:0] signed.",
         "function [69:0] coef; input [4:0] k; begin", "    case (k)"]
for k in range(len(ci.G)):
    v = 0
    for A in (ci.A1, ci.A2):
        for t in range(4):
            s, e = int(A[k, t, 0]), int(A[k, t, 1])
            v = (v << 8) | ({0: 0, 1: 1, -1: 3}[s] << 6) | (e & 63)
    v = (v << 6) | (int(ci.G[k]) & 63)
    lines.append(f"        5'd{k}: coef = 70'h{v:018x};")
lines += ["        default: coef = 70'h0;", "    endcase", "end endfunction"]
open(os.path.join(HERE, "cochlea_coef.vh"), "w").write("\n".join(lines) + "\n")
